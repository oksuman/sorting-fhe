// ============================================================================
// Main dispatcher
// ============================================================================
Ciphertext<DCRTPoly> indicator(const Ciphertext<DCRTPoly>& c,
                                const CryptoContext<DCRTPoly>& cc,
                                IndicatorFunc func,
                                const IndicatorConfig& cfg) {
    switch (func) {
    case IndicatorFunc::Ind0Naive:
        return indicatorInd0Naive(c, cc, cfg);
    case IndicatorFunc::Gaussian:
        return indicatorGaussian(c, cc, cfg);
    case IndicatorFunc::CKK20:
        return indicatorCKK20(c, cc, cfg);
    case IndicatorFunc::LLNK22:
        return indicatorLLNK22(c, cc, cfg);
    case IndicatorFunc::Sinc:
        return indicatorSinc(c, cc, cfg);
    default:
        throw std::runtime_error("Unknown indicator function type");
    }
}

// ============================================================================
// Depth calculation
// ============================================================================
int getIndicatorDepth(IndicatorFunc func, const IndicatorConfig& cfg) {
    switch (func) {
    case IndicatorFunc::Ind0Naive:
    case IndicatorFunc::Gaussian:
    case IndicatorFunc::Sinc: {
        // Chebyshev series depth: ceil(log2(degree)) + 1 for PS algorithm
        int d = cfg.degree;
        if (d <= 0) return 0;
        return static_cast<int>(std::ceil(std::log2(d))) + 1;
    }
    case IndicatorFunc::CKK20: {
        // Each g composition: 3 levels (degree 7 polynomial)
        // Each f composition: 3 levels (degree 7 polynomial)
        // indicatorAdv does: 2 signAdv calls + 1 multiplication
        // signAdv does: dg * g + df * f compositions
        int g_depth = 3; // degree 7 -> 3 levels
        int f_depth = 3;
        int sign_depth = cfg.comp.dg * g_depth + cfg.comp.df * f_depth;
        // Two sign evaluations + one multiplication
        return 2 * sign_depth + 1;
    }
    case IndicatorFunc::LLNK22:
        // Depends on precomputed polynomial structure
        // Will be determined from coefficient files
        return 0; // Placeholder
    default:
        return 0;
    }
}

