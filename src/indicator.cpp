// ============================================================================
// Ind0 Naive: Direct Chebyshev approximation of indicator at 0
// ============================================================================
Ciphertext<DCRTPoly> indicatorInd0Naive(const Ciphertext<DCRTPoly>& c,
                                         const CryptoContext<DCRTPoly>& cc,
                                         const IndicatorConfig& cfg) {
    double epsilon = cfg.getEpsilon();

    // Approximate the function: f(x) = 1 if |x| < epsilon, 0 otherwise
    // Using direct Chebyshev approximation (will have Gibbs phenomenon)
    return cc->EvalChebyshevFunction(
        [epsilon](double x) -> double {
            return (std::abs(x) < epsilon) ? 1.0 : 0.0;
        },
        c, -1.0, 1.0, cfg.degree);
}

// ============================================================================
// Gaussian: e^{-kx^2} approximation
// ============================================================================
Ciphertext<DCRTPoly> indicatorGaussian(const Ciphertext<DCRTPoly>& c,
                                        const CryptoContext<DCRTPoly>& cc,
                                        const IndicatorConfig& cfg) {
    double epsilon = cfg.getEpsilon();
    double k = computeGaussianK(epsilon); // k such that e^{-k*eps^2} ~ 2^{-10}

    // Approximate the Gaussian function e^{-kx^2}
    return cc->EvalChebyshevFunction(
        [k](double x) -> double { return std::exp(-k * x * x); },
        c, -1.0, 1.0, cfg.degree);
}

// ============================================================================
// CKK20: Comparison-based indicator using signAdv
// f(x) = (1 - sign(x - epsilon)) * sign(x + epsilon) / 4 + 0.5
// Outputs ~1 when -epsilon < x < epsilon, ~0 otherwise
// ============================================================================
Ciphertext<DCRTPoly> indicatorCKK20(const Ciphertext<DCRTPoly>& c,
                                     const CryptoContext<DCRTPoly>& cc,
                                     const IndicatorConfig& cfg) {
    int dg = cfg.comp.dg;
    int df = cfg.comp.df;

    // Use MEHP24's indicatorAdv implementation
    // indicatorAdv computes: sign(c + eps) * (1 - sign(c - eps))
    // where sign outputs values in [-1, 1], normalized to [0, 1]

    // Scale input to match indicatorAdv's expected range
    // indicatorAdv expects b parameter (range bound)
    double b = 1.0; // Our input is already in [-1, 1]

    return mehp24::utils::indicatorAdv(c, b, dg, df);
}

